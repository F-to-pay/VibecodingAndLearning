/*
 * main.c — открывает сразу несколько вкладок в браузере (соцсети и что угодно ещё).
 *
 * Идея простая: у нас есть список ссылок, и для каждой мы запускаем
 * системную команду "открыть эту ссылку в браузере по умолчанию".
 * На Linux это делает утилита `xdg-open` (она уже есть почти в любом
 * дистрибутиве с графическим окружением).
 *
 * Как это работает под капотом:
 *   1. fork()   — создаёт копию текущего процесса ("клонирует" программу).
 *   2. execvp() — в дочернем процессе ПОДМЕНЯЕТ его код на код команды
 *                 xdg-open, передавая ей ссылку как аргумент.
 *   3. waitpid()/не ждём — родительский процесс может либо ждать ребёнка,
 *                 либо сразу бежать дальше и запускать следующую вкладку.
 *
 * Мы НЕ используем system(), потому что:
 *   - system() каждый раз запускает /bin/sh, это медленнее;
 *   - если ссылка вдруг придёт из непроверенного источника, system()
 *     уязвим к shell-инъекциям (ссылка пройдёт через интерпретатор shell).
 *     execvp() передаёт аргумент напрямую программе, без shell — безопаснее.
 *
 * А на Windows всё иначе: там нет ни fork(), ни execvp(), ни xdg-open.
 * Зато есть функция WinAPI ShellExecuteA() — это ровно то, что делает
 * Проводник, когда ты дважды кликаешь по ярлыку со ссылкой: система
 * сама смотрит, какой браузер назначен "по умолчанию", и отдаёт ему URL.
 * Какой код собирать — решает препроцессор через #ifdef _WIN32 (см. ниже).
 *
 * Компиляция (Linux/macOS):   gcc -Wall -Wextra -o open_tabs main.c
 * Компиляция (Windows, MinGW): gcc -Wall -Wextra -o open_tabs.exe main.c -lshell32 -lole32
 * Компиляция (Windows, MSVC):  cl /utf-8 /W4 main.c
 *   (/utf-8 — чтобы MSVC прочитал этот файл как UTF-8, а не как кракозябры
 *    в кодировке Windows-1251; библиотеки MSVC подтянет сам, см. #pragma ниже)
 *
 * Запуск:      ./open_tabs        (Linux/macOS)
 *              open_tabs.exe      (Windows)
 */

#include <stdio.h>      /* printf, perror — вывод в консоль и ошибок */
#include <stdlib.h>     /* EXIT_SUCCESS, EXIT_FAILURE */

/*
 * _WIN32 — макрос, который компилятор сам определяет, когда собирает
 * под Windows (причём и под 32-, и под 64-битную — название историческое).
 * Всё, что между #ifdef _WIN32 и #else, на Linux просто выкидывается
 * препроцессором ещё до компиляции, и наоборот.
 */
#ifdef _WIN32
    /*
     * WIN32_LEAN_AND_MEAN говорит windows.h: "не тащи всё подряд".
     * Без него windows.h подключает кучу редко нужного барахла
     * (сокеты старого образца, криптографию и т.п.), и компиляция
     * тупо медленнее.
     */
    #define WIN32_LEAN_AND_MEAN
    #include <windows.h>    /* базовые типы WinAPI, SetConsoleOutputCP() */
    #include <shellapi.h>   /* ShellExecuteA() — "открыть что-то как Проводник" */
    #include <objbase.h>    /* CoInitializeEx() — инициализация COM, см. main() */

    /*
     * #pragma comment(lib, ...) — фишка MSVC: просит линкер самому
     * подключить нужные .lib, чтобы не писать их в командной строке.
     * MinGW (gcc) эту прагму игнорирует, поэтому для него библиотеки
     * указаны в Makefile через -lshell32 -lole32.
     */
    #ifdef _MSC_VER
        #pragma comment(lib, "shell32.lib")
        #pragma comment(lib, "ole32.lib")
    #endif
#else
    #include <unistd.h>     /* fork(), execvp() — работа с процессами */
    #include <sys/wait.h>   /* waitpid() — ожидание завершения дочернего процесса */
#endif

/*
 * Список ссылок, которые нужно открыть.
 * Массив строк (const char *) завершается указателем NULL —
 * это классический приём в C, чтобы знать, где список заканчивается,
 * не передавая отдельно его длину.
 *
 * Хочешь открывать другие сайты — просто меняй/добавляй строки тут.
 */
static const char *urls[] = {
    "https://vk.com",
    "https://t.me",
    "https://youtube.com",
    "https://x.com",
    "https://instagram.com",
    NULL /* маркер конца списка */
};

#ifdef _WIN32

/*
 * open_url — Windows-версия: открывает одну ссылку в браузере по умолчанию.
 *
 * Возвращает:
 *   0  — если Windows приняла ссылку и передала её браузеру;
 *  -1  — если ShellExecuteA() вернула ошибку.
 */
static int open_url(const char *url)
{
    /*
     * ShellExecuteA(окно, действие, что_открыть, параметры, папка, как_показать):
     *   NULL          — у нас консольная программа, родительского окна нет;
     *   "open"        — действие "открыть" (как двойной клик);
     *   url           — собственно ссылка;
     *   NULL, NULL    — дополнительных параметров и рабочей папки не надо;
     *   SW_SHOWNORMAL — показать окно браузера нормально, не свёрнутым.
     *
     * Буква 'A' в конце — это "ANSI"-версия, принимающая обычные char-строки.
     * Есть ещё ShellExecuteW для "широких" wchar_t-строк (UTF-16), но наши
     * ссылки — чистый ASCII, так что возиться с конвертацией незачем.
     *
     * Почему не system("start https://..."), как советует половина
     * интернета? По той же причине, что и на Linux: system() запускает
     * cmd.exe, а символ '&' в ссылке (а он в ссылках сплошь и рядом:
     * ?a=1&b=2) cmd воспримет как "а теперь выполни следующую команду".
     * ShellExecuteA() никакой оболочки не запускает — ссылка идёт как есть.
     */
    HINSTANCE result = ShellExecuteA(NULL, "open", url, NULL, NULL, SW_SHOWNORMAL);

    /*
     * Самая уродливая часть WinAPI: ShellExecuteA() по историческим
     * причинам (привет из 16-битной Windows 3.x) возвращает не нормальный
     * код ошибки, а HINSTANCE, который надо привести к числу.
     * Всё, что больше 32, — успех; 32 и меньше — код ошибки.
     * INT_PTR — целое того же размера, что и указатель, чтобы
     * на 64-битной системе ничего не обрезалось при приведении.
     */
    if ((INT_PTR)result <= 32) {
        /*
         * perror() тут бесполезен: WinAPI не пишет ошибки в errno.
         * Поэтому просто печатаем код, который вернула функция
         * (например, 2 — "файл не найден", 31 — "нет программы для
         * этого типа ссылок", то есть браузер по умолчанию не назначен).
         */
        fprintf(stderr, "ShellExecute: не смог открыть %s (код %d)\n",
                url, (int)(INT_PTR)result);
        return -1;
    }

    /*
     * Никаких pid тут нет: ShellExecuteA() не создаёт "наш" процесс,
     * она просит систему, а система уже сама решает — запустить новый
     * браузер или открыть вкладку в уже запущенном.
     */
    printf("Открываю: %s\n", url);
    return 0;
}

#else /* всё, что ниже, — для Linux и macOS */

/*
 * На macOS аналог xdg-open называется просто `open` (он встроен в систему).
 * __APPLE__ — макрос, который компилятор определяет при сборке под macOS.
 * Остальной код (fork/execvp) одинаковый: обе системы — POSIX.
 */
#ifdef __APPLE__
    #define OPENER "open"
#else
    #define OPENER "xdg-open"
#endif

/*
 * open_url — POSIX-версия (Linux/macOS): открывает одну ссылку в браузере по умолчанию.
 *
 * Возвращает:
 *   0  — если процесс успешно запущен (не гарантирует, что браузер
 *        реально открылся, просто что команда стартовала);
 *  -1  — если fork() не смог создать процесс.
 */
static int open_url(const char *url)
{
    pid_t pid = fork(); /* "раздваиваем" процесс */

    if (pid < 0) {
        /* fork() не смог создать дочерний процесс (например, кончилась память) */
        perror("fork");
        return -1;
    }

    if (pid == 0) {
        /*
         * Мы в ДОЧЕРНЕМ процессе.
         * execvp() ищет программу OPENER ("xdg-open" или "open") в PATH (буква 'p' в имени —
         * "path") и заменяет текущий процесс на неё.
         *
         * Аргументы для execvp — это то же самое, что argv в main():
         *   argv[0] — имя программы (по конвенции),
         *   argv[1] — ссылка, которую надо открыть,
         *   argv[2] — NULL, конец списка аргументов.
         */
        char *argv[] = { OPENER, (char *)url, NULL };

        execvp(OPENER, argv);

        /*
         * Если мы дошли до этой строки — execvp() провалился
         * (например, xdg-open не установлен). В нормальной ситуации
         * execvp() не возвращает управление вообще.
         */
        perror("execvp");
        _exit(EXIT_FAILURE); /* _exit, а не exit — чтобы не трогать буферы родителя */
    }

    /*
     * Мы в РОДИТЕЛЬСКОМ процессе (pid — это PID ребёнка).
     * Здесь можно либо подождать ребёнка (waitpid), либо не ждать
     * и сразу запускать следующую вкладку — так вкладки откроются
     * параллельно, а не одна за другой.
     */
    printf("Открываю: %s (pid %d)\n", url, (int)pid);
    return 0;
}

#endif /* _WIN32 */

int main(void)
{
    int opened = 0; /* сколько ссылок РЕАЛЬНО удалось отправить в браузер */

#ifdef _WIN32
    /*
     * Консоль Windows по умолчанию живёт в древней кодировке (CP866 или
     * CP1251), а наши printf'ы печатают русский текст в UTF-8 — без этой
     * строчки вместо "Открываю" увидишь "РћС‚РєСЂС‹РІР°СЋ".
     * SetConsoleOutputCP(CP_UTF8) переключает консоль на UTF-8
     * (только для этого окна и только пока программа работает).
     */
    SetConsoleOutputCP(CP_UTF8);

    /*
     * Microsoft в документации к ShellExecute прямо пишет: "инициализируй
     * COM перед вызовом". Некоторые обработчики ссылок внутри Windows
     * сделаны на COM, и без инициализации они могут молча не сработать.
     * Для обычного браузера это обычно не нужно, но "обычно" — плохое
     * слово для программы, так что делаем по инструкции.
     * COINIT_DISABLE_OLE1DDE отключает древний механизм DDE из 90-х,
     * который тоже рекомендуют выключать.
     */
    HRESULT com = CoInitializeEx(NULL, COINIT_APARTMENTTHREADED | COINIT_DISABLE_OLE1DDE);
#endif

    /*
     * Проходим по массиву urls, пока не встретим NULL.
     * Для каждой ссылки запускаем отдельный процесс браузера
     * и считаем только те, что реально запустились.
     */
    for (int i = 0; urls[i] != NULL; i++) {
        if (open_url(urls[i]) == 0) {
            opened++;
        }
    }

    /*
     * Мы намеренно НЕ вызываем waitpid() тут в цикле для каждого дочернего
     * процесса сразу — иначе вкладки открывались бы по одной, дожидаясь
     * закрытия предыдущего процесса-запускателя. xdg-open обычно сам
     * быстро завершается (он лишь передаёт команду браузеру и выходит),
     * так что дочерние процессы просто станут "зомби" на короткое время,
     * пока не завершится программа. Для чистоты можно было бы собрать
     * все pid в массив и подождать их в конце через waitpid — оставляю
     * это как готовое место для расширения, если понадобится.
     */

#ifdef _WIN32
    /*
     * Каждому успешному CoInitializeEx — свой CoUninitialize,
     * как каждому malloc — свой free. Если инициализация провалилась,
     * "деинициализировать" нечего.
     */
    if (SUCCEEDED(com)) {
        CoUninitialize();
    }
#endif

    /*
     * Раньше тут печаталась длина массива — то есть программа честно
     * врала "открыто 5", даже если не открылось ничего. Теперь печатаем
     * реальный счётчик, а если хоть одна ссылка не открылась — выходим
     * с кодом ошибки, чтобы это было видно и из скриптов.
     */
    printf("Готово. Открыто ссылок: %d\n", opened);
    return (opened == (int)(sizeof(urls) / sizeof(urls[0]) - 1)) ? EXIT_SUCCESS : EXIT_FAILURE;
}
