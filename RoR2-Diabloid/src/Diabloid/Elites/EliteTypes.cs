namespace Diabloid.Elites
{
    /// <summary>Наши элитки.</summary>
    public enum EliteKind
    {
        Titan,        // призывает 4 копии (без наград), хп ×6, размер ×2
        Bloodsucker,  // раненый — сосёт хп у всех в радиусе; 10% полученного урона не лечится (как у Митрикса)
        Clockmaker,   // замедляет врагов в радиусе: бег 70%, атака 30%
        Power,        // урон ×5 при обычном здоровье (до 0.5.0 — "стекло" с хп ×0.1)
    }

    /// <summary>
    /// Когда элитка может появляться. Названия совпадают с ванильными тирами:
    /// Tier1 — с первого этапа (как Пылающие), Tier1Late — с третьего (как Позолоченные),
    /// Tier2 — после лупа (как Малахитовые).
    /// </summary>
    /// <remarks>Это значения в конфиге — не переименовывать, иначе у людей слетят настройки.</remarks>
    public enum EliteTierChoice
    {
        Disabled,
        Tier1,
        Tier1Late,
        Tier2,
    }
}
